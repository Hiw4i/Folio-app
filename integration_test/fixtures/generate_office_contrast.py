"""Generate synthetic, offline DOCX/PPTX fixtures embedded only in GPU tests."""
import base64
import io
from pathlib import Path
import textwrap
import zipfile

from docx import Document
from docx.shared import Inches, Pt
from PIL import Image, ImageDraw
from pptx import Presentation
from pptx.util import Inches as PptInches


def contrast_image():
    image = Image.new('RGB', (720, 960), '#080808')
    draw = ImageDraw.Draw(image)
    draw.rectangle((360, 0, 719, 959), fill='#f8f8f8')
    for x in range(0, 720, 12):
        draw.rectangle((x, 0, x + 5, 959),
                       fill='#282828' if x < 360 else '#a0a0a0')
    data = io.BytesIO()
    image.save(data, format='PNG')
    return data.getvalue()


def docx(image):
    document = Document()
    section = document.sections[0]
    section.page_width, section.page_height = Inches(6), Inches(9)
    section.top_margin = section.bottom_margin = Inches(0)
    section.left_margin = section.right_margin = Inches(0)
    paragraph = document.paragraphs[0] if document.paragraphs else document.add_paragraph()
    paragraph.paragraph_format.space_after = Pt(0)
    paragraph.add_run().add_picture(io.BytesIO(image), width=Inches(6))
    document.add_paragraph('Office selection regression text for copying and dragging.')
    data = io.BytesIO()
    document.save(data)
    # Word's default template contains large, irrelevant theme/style tables.
    # Retain only the document's image relationship and use renderer defaults.
    with zipfile.ZipFile(data) as original:
        parts = {name: original.read(name) for name in
                 ('[Content_Types].xml', '_rels/.rels', 'word/document.xml',
                  'word/media/image1.png')}
    parts['word/_rels/document.xml.rels'] = b'''<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId9" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="media/image1.png"/></Relationships>'''
    # python-docx's actual image relationship ID is read from the generated XML.
    import re
    image_id = re.search(rb'r:embed="([^"]+)"', parts['word/document.xml'])[1]
    parts['word/_rels/document.xml.rels'] = parts['word/_rels/document.xml.rels'].replace(b'rId9', image_id)
    result = io.BytesIO()
    with zipfile.ZipFile(result, 'w', zipfile.ZIP_DEFLATED) as output:
        for name, content in parts.items():
            output.writestr(name, content)
    return result.getvalue()


def pptx(image):
    deck = Presentation()
    deck.slide_width, deck.slide_height = PptInches(6), PptInches(9)
    slide = deck.slides.add_slide(deck.slide_layouts[6])
    slide.shapes.add_picture(io.BytesIO(image), 0, 0, width=PptInches(6))
    slide.shapes.add_textbox(0, PptInches(8.2), PptInches(6), PptInches(.5)).text = (
        'Office selection regression text for copying and dragging.')
    data = io.BytesIO()
    deck.save(data)
    return data.getvalue()


if __name__ == '__main__':
    image = contrast_image()
    lines = ['// Generated by generate_office_contrast.py; synthetic OOXML, no user documents.',
             '// First page/slide: dark left and light right, with high-frequency stripes.', '']
    for name, payload in [('docx', docx(image)), ('pptx', pptx(image))]:
        lines.append(f'const {name}ContrastBase64 =')
        lines.extend(f"    '{chunk}'" for chunk in textwrap.wrap(base64.b64encode(payload).decode(), 100))
        lines[-1] += ';'
        lines.append('')
    Path(__file__).with_name('office_contrast.dart').write_text('\n'.join(lines), encoding='utf-8')
